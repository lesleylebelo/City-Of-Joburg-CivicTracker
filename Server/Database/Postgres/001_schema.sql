-- Fresh, isolated Supabase/PostgreSQL database only. No data is imported.
-- One-time setup: intentionally fails if civictrack already exists.
BEGIN;
CREATE SCHEMA civictrack;
-- TABLE: authorised_employees
-- Stores pre-approved employees who are allowed to register
-- as administrators. Must exist before administrators table.
-- ============================================================
CREATE TABLE civictrack.authorised_employees (
    authorised_id   INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_number varchar(20)  NOT NULL,
    full_names      varchar(100) NOT NULL,
    role            varchar(100) NOT NULL,
    is_registered   boolean           NULL CONSTRAINT df_authorised_is_registered DEFAULT (FALSE),
    created_at      timestamptz      NULL CONSTRAINT df_authorised_created_at    DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_authorised_employees PRIMARY KEY (authorised_id),
    CONSTRAINT uq_authorised_employee_number UNIQUE (employee_number)
);

-- ============================================================
-- TABLE: administrators
-- Stores admin accounts linked to authorised_employees.
-- ============================================================
CREATE TABLE civictrack.administrators (
    admin_id        INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    full_names      varchar(100) NOT NULL,
    email           varchar(150) NOT NULL,
    employee_number varchar(20)  NOT NULL,
    password_hash   varchar(255) NOT NULL,
    is_active       boolean           NULL CONSTRAINT df_admin_is_active   DEFAULT (TRUE),
    created_at      timestamptz      NULL CONSTRAINT df_admin_created_at  DEFAULT (CURRENT_TIMESTAMP),
    updated_at      timestamptz      NULL CONSTRAINT df_admin_updated_at  DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_administrators PRIMARY KEY (admin_id),
    CONSTRAINT uq_admin_employee_number UNIQUE (employee_number),
    CONSTRAINT uq_admin_email           UNIQUE (email),
    CONSTRAINT fk_admin_authorised FOREIGN KEY (employee_number)
        REFERENCES civictrack.authorised_employees (employee_number)
);

-- ============================================================
-- TABLE: residents
-- Stores resident (public user) accounts.
-- ============================================================
CREATE TABLE civictrack.residents (
    resident_id   INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    full_names    varchar(100) NOT NULL,
    email         varchar(150) NOT NULL,
    phone_number  varchar(15)  NOT NULL,
    password_hash varchar(255) NOT NULL,
    is_active     boolean           NULL CONSTRAINT df_residents_is_active   DEFAULT (TRUE),
    created_at    timestamptz      NULL CONSTRAINT df_residents_created_at  DEFAULT (CURRENT_TIMESTAMP),
    updated_at    timestamptz      NULL CONSTRAINT df_residents_updated_at  DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_residents PRIMARY KEY (resident_id),
    CONSTRAINT uq_residents_email UNIQUE (email)
);

-- ============================================================
-- TABLE: reported_issues
-- Stores civic issues reported by residents.
-- ============================================================
CREATE TABLE civictrack.reported_issues (
    issue_id          INT            GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    resident_id       INT            NOT NULL,
    title             varchar(150)  NOT NULL,
    description       text  NOT NULL,
    category          varchar(50)   NOT NULL,
    status            varchar(20)   NULL CONSTRAINT df_issues_status   DEFAULT ('Pending'),
    priority          varchar(10)   NULL CONSTRAINT df_issues_priority DEFAULT ('Medium'),
    location_address  varchar(255)  NOT NULL,
    latitude          DECIMAL(10, 8) NULL,
    longitude         DECIMAL(11, 8) NULL,
    image_url         varchar(500)  NULL,
    assigned_admin_id INT            NULL,
    admin_notes       text  NULL,
    resolved_at       timestamptz       NULL,
    created_at        timestamptz       NULL CONSTRAINT df_issues_created_at DEFAULT (CURRENT_TIMESTAMP),
    updated_at        timestamptz       NULL CONSTRAINT df_issues_updated_at DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_reported_issues PRIMARY KEY (issue_id),

    CONSTRAINT fk_issues_resident FOREIGN KEY (resident_id)
        REFERENCES civictrack.residents (resident_id) ON DELETE CASCADE,

    CONSTRAINT fk_issues_admin FOREIGN KEY (assigned_admin_id)
        REFERENCES civictrack.administrators (admin_id) ON DELETE SET NULL,

    CONSTRAINT chk_issues_status CHECK (
        status IN ('Pending', 'In Progress', 'Resolved', 'Rejected')
    ),
    CONSTRAINT chk_issues_priority CHECK (
        priority IN ('Low', 'Medium', 'High')
    ),
    CONSTRAINT chk_issues_category CHECK (
        category IN ('Pothole', 'Broken Streetlight', 'Water Leak', 'Sewage',
                     'Illegal Dumping', 'Vandalism', 'Other')
    )
);

-- Indexes for reported_issues
CREATE INDEX idx_issues_status   ON civictrack.reported_issues (status);
CREATE INDEX idx_issues_category ON civictrack.reported_issues (category);
CREATE INDEX idx_issues_resident ON civictrack.reported_issues (resident_id);

-- ============================================================
-- TABLE: development_projects
-- Stores infrastructure/development projects created by admins.
-- ============================================================
CREATE TABLE civictrack.development_projects (
    project_id        INT            GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title             varchar(200)  NOT NULL,
    description       text  NOT NULL,
    category          varchar(50)   NOT NULL,
    status            varchar(20)   NULL CONSTRAINT df_projects_status     DEFAULT ('Planned'),
    location_address  varchar(255)  NOT NULL,
    latitude          DECIMAL(10, 8) NULL,
    longitude         DECIMAL(11, 8) NULL,
    start_date        DATE           NULL,
    expected_end_date DATE           NULL,
    actual_end_date   DATE           NULL,
    image_url         varchar(500)  NULL,
    created_by_admin  INT            NOT NULL,
    created_at        timestamptz       NULL CONSTRAINT df_projects_created_at DEFAULT (CURRENT_TIMESTAMP),
    updated_at        timestamptz       NULL CONSTRAINT df_projects_updated_at DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_development_projects PRIMARY KEY (project_id),

    CONSTRAINT fk_projects_admin FOREIGN KEY (created_by_admin)
        REFERENCES civictrack.administrators (admin_id),

    CONSTRAINT chk_projects_status CHECK (
        status IN ('Planned', 'In Progress', 'On Hold', 'Completed')
    ),
    CONSTRAINT chk_projects_category CHECK (
        category IN ('Road Construction', 'Building Construction', 'Water Infrastructure',
                     'Electrical Infrastructure', 'Parks & Recreation', 'Other')
    )
);

CREATE INDEX idx_projects_status ON civictrack.development_projects (status);

-- ============================================================
-- TABLE: events
-- Stores community events created by admins.
-- ============================================================
CREATE TABLE civictrack.events (
    event_id         INT            GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title            varchar(200)  NOT NULL,
    description      text  NOT NULL,
    category         varchar(50)   NULL CONSTRAINT df_events_category     DEFAULT ('Community Meeting'),
    location_address varchar(255)  NOT NULL,
    latitude         DECIMAL(10, 8) NULL,
    longitude        DECIMAL(11, 8) NULL,
    event_date       DATE           NOT NULL,
    start_time       time(6)        NOT NULL,
    end_time         time(6)        NULL,
    image_url        varchar(500)  NULL,
    is_published     boolean            NULL CONSTRAINT df_events_is_published  DEFAULT (FALSE),
    created_by_admin INT            NOT NULL,
    created_at       timestamptz       NULL CONSTRAINT df_events_created_at    DEFAULT (CURRENT_TIMESTAMP),
    updated_at       timestamptz       NULL CONSTRAINT df_events_updated_at    DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_events PRIMARY KEY (event_id),

    CONSTRAINT fk_events_admin FOREIGN KEY (created_by_admin)
        REFERENCES civictrack.administrators (admin_id),

    CONSTRAINT chk_events_category CHECK (
        category IN ('Community Meeting', 'Public Hearing', 'Maintenance',
                     'Festival', 'Health', 'Other')
    )
);

CREATE INDEX idx_events_date ON civictrack.events (event_date);

-- ============================================================
-- TABLE: notices
-- Stores public notices/announcements created by admins.
-- ============================================================
CREATE TABLE civictrack.notices (
    notice_id        INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title            varchar(200) NOT NULL,
    content          text NOT NULL,
    category         varchar(20)  NULL CONSTRAINT df_notices_category      DEFAULT ('General'),
    is_published     boolean           NULL CONSTRAINT df_notices_is_published   DEFAULT (FALSE),
    published_at     timestamptz      NULL,
    expires_at       timestamptz      NULL,
    created_by_admin INT           NOT NULL,
    created_at       timestamptz      NULL CONSTRAINT df_notices_created_at     DEFAULT (CURRENT_TIMESTAMP),
    updated_at       timestamptz      NULL CONSTRAINT df_notices_updated_at     DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_notices PRIMARY KEY (notice_id),

    CONSTRAINT fk_notices_admin FOREIGN KEY (created_by_admin)
        REFERENCES civictrack.administrators (admin_id),

    CONSTRAINT chk_notices_category CHECK (
        category IN ('General', 'Water', 'Electricity', 'Roads',
                     'Safety', 'Health', 'Other')
    )
);

CREATE INDEX idx_notices_published ON civictrack.notices (is_published);

-- ============================================================
-- TABLE: notifications
-- Stores in-app notifications sent to residents.
-- ============================================================
CREATE TABLE civictrack.notifications (
    notification_id INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    resident_id     INT           NOT NULL,
    type            varchar(30)  NOT NULL,
    title           varchar(200) NOT NULL,
    message         text NOT NULL,
    is_read         boolean           NULL CONSTRAINT df_notifications_is_read   DEFAULT (FALSE),
    reference_id    INT           NULL,
    reference_type  varchar(50)  NULL,
    created_at      timestamptz      NULL CONSTRAINT df_notifications_created_at DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_notifications PRIMARY KEY (notification_id),

    CONSTRAINT fk_notifications_resident FOREIGN KEY (resident_id)
        REFERENCES civictrack.residents (resident_id) ON DELETE CASCADE,

    CONSTRAINT chk_notifications_type CHECK (
        type IN ('Issue Update', 'New Notice', 'New Event',
                 'New Poll', 'Project Update', 'General')
    )
);

CREATE INDEX idx_notifications_res ON civictrack.notifications (resident_id, is_read);

-- ============================================================
-- TABLE: password_reset_tokens
-- Stores OTP tokens used for password reset.
-- ============================================================
CREATE TABLE civictrack.password_reset_tokens (
    token_id   INT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_type  varchar(10) NOT NULL,
    user_id    INT          NOT NULL,
    otp_code   varchar(6)  NOT NULL,
    is_used    boolean          NULL CONSTRAINT df_tokens_is_used   DEFAULT (FALSE),
    expires_at timestamptz     NOT NULL,
    created_at timestamptz     NULL CONSTRAINT df_tokens_created_at DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_password_reset_tokens PRIMARY KEY (token_id),

    CONSTRAINT chk_tokens_user_type CHECK (
        user_type IN ('resident', 'admin')
    )
);

CREATE INDEX idx_reset_tokens ON civictrack.password_reset_tokens (user_id, user_type, is_used);

-- ============================================================
-- TABLE: polls
-- Stores community polls created by admins.
-- ============================================================
CREATE TABLE civictrack.polls (
    poll_id          INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    question         varchar(300) NOT NULL,
    description      text NULL,
    is_active        boolean           NULL CONSTRAINT df_polls_is_active   DEFAULT (TRUE),
    start_date       timestamptz      NULL CONSTRAINT df_polls_start_date  DEFAULT (CURRENT_TIMESTAMP),
    end_date         timestamptz      NULL,
    created_by_admin INT           NOT NULL,
    created_at       timestamptz      NULL CONSTRAINT df_polls_created_at  DEFAULT (CURRENT_TIMESTAMP),
    updated_at       timestamptz      NULL CONSTRAINT df_polls_updated_at  DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_polls PRIMARY KEY (poll_id),

    CONSTRAINT fk_polls_admin FOREIGN KEY (created_by_admin)
        REFERENCES civictrack.administrators (admin_id)
);

CREATE INDEX idx_polls_active ON civictrack.polls (is_active);

-- ============================================================
-- TABLE: poll_options
-- Stores the answer options for each poll.
-- ============================================================
CREATE TABLE civictrack.poll_options (
    option_id     INT           GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    poll_id       INT           NOT NULL,
    option_text   varchar(200) NOT NULL,
    display_order INT           NULL CONSTRAINT df_poll_options_display_order DEFAULT (0),

    CONSTRAINT pk_poll_options PRIMARY KEY (option_id),

    CONSTRAINT fk_options_poll FOREIGN KEY (poll_id)
        REFERENCES civictrack.polls (poll_id) ON DELETE CASCADE
);

-- ============================================================
-- TABLE: poll_votes
-- Stores votes cast by residents on polls.
-- One vote per resident per poll (enforced by unique constraint).
-- ============================================================
CREATE TABLE civictrack.poll_votes (
    vote_id     INT      GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    poll_id     INT      NOT NULL,
    option_id   INT      NOT NULL,
    resident_id INT      NOT NULL,
    voted_at    timestamptz NULL CONSTRAINT df_poll_votes_voted_at DEFAULT (CURRENT_TIMESTAMP),

    CONSTRAINT pk_poll_votes PRIMARY KEY (vote_id),

    CONSTRAINT uq_unique_vote UNIQUE (poll_id, resident_id),

    CONSTRAINT fk_votes_poll FOREIGN KEY (poll_id)
        REFERENCES civictrack.polls (poll_id),

    CONSTRAINT fk_votes_option FOREIGN KEY (option_id)
        REFERENCES civictrack.poll_options (option_id),

    CONSTRAINT fk_votes_resident FOREIGN KEY (resident_id)
        REFERENCES civictrack.residents (resident_id)
);

